#!/usr/bin/env bash
set -Eeuo pipefail

WORKSPACE_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd -P)"
OUTPUT_ROOT="${1:-${CAMERA_WS_UPLOAD_DIR:-${WORKSPACE_DIR}/upload}}"
mkdir -p "$OUTPUT_ROOT"
OUTPUT_ROOT="$(cd -- "$OUTPUT_ROOT" && pwd -P)"

staging_root="$(mktemp -d "${OUTPUT_ROOT}/.camera-ws-staging.XXXXXX")"
cleanup() {
  rm -rf -- "$staging_root"
}
trap cleanup EXIT

stage="${staging_root}/camera_ws"
mkdir -p "$stage"

rsync -rlptL \
  --exclude='/.git/' \
  --exclude='/build/' \
  --exclude='/log/' \
  --exclude='/upload/' \
  --exclude='/work/' \
  --exclude='/downloads/' \
  --exclude='/jsons/' \
  --exclude='/vendor/compat/usr/share/doc/' \
  --exclude='/.secrets/' \
  --exclude='__pycache__/' \
  --exclude='*.pyc' \
  --exclude='*.bag' \
  --exclude='*.db3' \
  --exclude='/CameraSDK*' \
  --exclude='/Linux_CameraSDK*' \
  --include='/third_party/insta360_ros_driver/lib/jsons/.gitkeep' \
  --exclude='/third_party/insta360_ros_driver/lib/jsons/*' \
  --exclude='/third_party/insta360_ros_driver/lib/libCameraSDK.so' \
  --include='/third_party/insta360_ros_driver/include/camera/.gitkeep' \
  --exclude='/third_party/insta360_ros_driver/include/camera/*' \
  --include='/third_party/insta360_ros_driver/include/stream/.gitkeep' \
  --exclude='/third_party/insta360_ros_driver/include/stream/*' \
  --exclude='/install/insta360_ros_driver/share/insta360_ros_driver/lib/libCameraSDK.so' \
  --include='/install/insta360_ros_driver/share/insta360_ros_driver/lib/jsons/.gitkeep' \
  --exclude='/install/insta360_ros_driver/share/insta360_ros_driver/lib/jsons/*' \
  "${WORKSPACE_DIR}/" "$stage/"

printf '%s\n' \
  'Generated by sh/maintenance/package_upload.sh.' \
  'CameraSDK is intentionally excluded and must be installed by start.sh.' \
  > "${stage}/.upload-generated"

for forbidden in \
  "jsons/camera_conf_Insta360_X3.json" \
  "third_party/insta360_ros_driver/lib/libCameraSDK.so" \
  "third_party/insta360_ros_driver/include/camera/camera.h" \
  "third_party/insta360_ros_driver/include/stream/stream_delegate.h" \
  "install/insta360_ros_driver/share/insta360_ros_driver/lib/libCameraSDK.so"; do
  [[ ! -e "${stage}/${forbidden}" ]] ||
    {
      printf 'ERROR: proprietary CameraSDK artifact was included: %s\n' "$forbidden" >&2
      exit 1
    }
done

if [[ -e "${OUTPUT_ROOT}/camera_ws" ]]; then
  [[ -f "${OUTPUT_ROOT}/camera_ws/.upload-generated" ]] ||
    {
      printf 'ERROR: refusing to replace non-generated directory: %s/camera_ws\n' "$OUTPUT_ROOT" >&2
      exit 1
    }
  rm -rf -- "${OUTPUT_ROOT}/camera_ws"
fi
mv "$stage" "${OUTPUT_ROOT}/camera_ws"

stamp="$(date +%Y%m%d_%H%M%S)"
archive="${OUTPUT_ROOT}/camera_ws-${stamp}.tar.gz"
tar -czf "$archive" -C "$OUTPUT_ROOT" camera_ws
sha256sum "$archive" > "${archive}.sha256"

cat > "${OUTPUT_ROOT}/UPLOAD_MANIFEST.md" <<EOF
# camera_ws upload bundle

- Directory: \`camera_ws/\`
- Archive: \`$(basename "$archive")\`
- Main entry: \`bash start.sh\`
- Bundled ROS: \`vendor/ros/jazzy\`
- CameraSDK: excluded; installed by \`start.sh\` on the target machine
- Build cache: excluded; installed runtime files are self-contained
- Logs, downloads, caches and local backups: excluded

First-time target setup:

\`\`\`bash
cd camera_ws
CAMERA_SDK_URL='https://.../CameraSDK.zip' bash start.sh --prepare-only
bash start.sh --camera x3 d455
\`\`\`

An existing SDK archive or extracted directory can also be supplied:

\`\`\`bash
bash start.sh --sdk-archive CameraSDK.zip --prepare-only
bash start.sh --sdk-dir CameraSDK --prepare-only
\`\`\`

Insta360 CameraSDK is proprietary. Obtain it from
https://www.insta360.com/sdk/home and follow the applicable license.
EOF

printf 'Upload directory: %s\n' "${OUTPUT_ROOT}/camera_ws"
printf 'Upload archive:   %s\n' "$archive"
printf 'Archive SHA256:   %s\n' "${archive}.sha256"
